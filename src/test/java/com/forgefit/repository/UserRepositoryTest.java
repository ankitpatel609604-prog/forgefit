package com.forgefit.repository;

import com.forgefit.model.User;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.autoconfigure.orm.jpa.DataJpaTest;
import org.springframework.test.context.TestPropertySource;

import java.util.Optional;

import static org.junit.jupiter.api.Assertions.*;

/**
 * Integration tests for UserRepository.
 * 
 * Tests database operations including user creation, retrieval, and email uniqueness constraints.
 * Uses @DataJpaTest for lightweight integration testing with in-memory H2 database.
 */
@DataJpaTest
@TestPropertySource(locations = "classpath:application-test.properties")
@DisplayName("UserRepository Integration Tests")
public class UserRepositoryTest {

    @Autowired
    private UserRepository userRepository;

    private User testUser;

    @BeforeEach
    void setUp() {
        testUser = new User();
        testUser.setFullName("John Doe");
        testUser.setEmail("john@example.com");
        testUser.setPassword("$2b$10$hashedPasswordHere"); // Simulated BCrypt hash
        testUser.setRole("USER");
    }

    @Test
    @DisplayName("Should save and retrieve a user by email")
    void testSaveAndFindByEmail() {
        // Arrange: Save test user
        User savedUser = userRepository.save(testUser);
        
        // Act: Retrieve user by email
        Optional<User> foundUser = userRepository.findByEmail("john@example.com");

        // Assert: User should be found with correct values
        assertTrue(foundUser.isPresent(), "User should be found by email");
        assertEquals("John Doe", foundUser.get().getFullName());
        assertEquals("john@example.com", foundUser.get().getEmail());
        assertEquals("USER", foundUser.get().getRole());
        assertNotNull(foundUser.get().getId());
        assertTrue(foundUser.get().getId() > 0);
    }

    @Test
    @DisplayName("Should return empty Optional for non-existent email")
    void testFindByEmailNotFound() {
        // Arrange: Save a user
        userRepository.save(testUser);

        // Act: Search for non-existent email
        Optional<User> result = userRepository.findByEmail("nonexistent@example.com");

        // Assert: Should return empty Optional
        assertFalse(result.isPresent(), "Optional should be empty for non-existent email");
    }

    @Test
    @DisplayName("Should enforce email uniqueness constraint")
    void testEmailUniquenessConstraint() {
        // Arrange: Save first user with email
        userRepository.save(testUser);

        // Arrange: Create second user with same email
        User duplicateUser = new User();
        duplicateUser.setFullName("Jane Doe");
        duplicateUser.setEmail("john@example.com"); // Same email
        duplicateUser.setPassword("$2b$10$differentHash");
        duplicateUser.setRole("USER");

        // Act & Assert: Second save should throw DataIntegrityViolationException
        assertThrows(org.springframework.dao.DataIntegrityViolationException.class, () -> {
            userRepository.save(duplicateUser);
            userRepository.flush(); // Force constraint validation
        }, "Should throw exception when saving duplicate email");
    }

    @Test
    @DisplayName("Should auto-generate ID on save")
    void testAutoGeneratedId() {
        // Arrange: User without ID
        assertNull(testUser.getId(), "ID should be null before save");

        // Act: Save user
        User savedUser = userRepository.save(testUser);

        // Assert: ID should be auto-generated
        assertNotNull(savedUser.getId(), "ID should be generated after save");
        assertTrue(savedUser.getId() > 0, "ID should be positive");
    }

    @Test
    @DisplayName("Should maintain password hash integrity")
    void testPasswordHashIntegrity() {
        // Arrange: User with BCrypt hash
        String bcryptHash = "$2b$10$4axnbGVqsBCamG2iIHuPnuLXJLV5DQ0WL8OKJkqbJ0YmCNm/mJ4pC";
        testUser.setPassword(bcryptHash);

        // Act: Save and retrieve
        userRepository.save(testUser);
        Optional<User> retrieved = userRepository.findByEmail(testUser.getEmail());

        // Assert: Password hash should be unchanged
        assertTrue(retrieved.isPresent());
        assertEquals(bcryptHash, retrieved.get().getPassword(), 
            "Password hash should remain unchanged");
    }

    @Test
    @DisplayName("Should handle case-sensitive email lookup")
    void testCaseSensitiveEmailLookup() {
        // Arrange: Save user with lowercase email
        userRepository.save(testUser);

        // Act: Search with different case
        Optional<User> result = userRepository.findByEmail("JOHN@EXAMPLE.COM");

        // Assert: Should not find (case-sensitive)
        // Note: This behavior may depend on database configuration
        // For H2 in this setup, this will be case-sensitive
        assertFalse(result.isPresent(), 
            "Email lookup should be case-sensitive");
    }

    @Test
    @DisplayName("Should correctly store and retrieve user role")
    void testRoleStorage() {
        // Arrange: Set role explicitly
        testUser.setRole("ADMIN");

        // Act: Save and retrieve
        User savedUser = userRepository.save(testUser);
        Optional<User> retrieved = userRepository.findByEmail(testUser.getEmail());

        // Assert: Role should be preserved
        assertTrue(retrieved.isPresent());
        assertEquals("ADMIN", retrieved.get().getRole(), "Role should be preserved");
    }

    @Test
    @DisplayName("Should store and retrieve full name with special characters")
    void testFullNameWithSpecialCharacters() {
        // Arrange: Full name with special characters
        testUser.setFullName("Jean-Paul O'Brien");

        // Act: Save and retrieve
        userRepository.save(testUser);
        Optional<User> retrieved = userRepository.findByEmail(testUser.getEmail());

        // Assert: Full name should be preserved exactly
        assertTrue(retrieved.isPresent());
        assertEquals("Jean-Paul O'Brien", retrieved.get().getFullName(), 
            "Full name with special characters should be preserved");
    }
}
